// Regenerates apps/docs/src/content/docs/api/reference.md from the blog demo
// app's OpenAPI 3.1 contract, so the docs site's API reference can never drift
// from the C# route tree. Chained into `bun reptar codegen` for the blog app
// and runnable standalone via `bun reptar docs:gen`.
//
// Output is deterministic: routes are grouped by first path segment and sorted,
// so only real contract changes move the file. CI gates it with
// `git diff --exit-code apps/docs/src/content/docs/api/`.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const ROOT = join(dirname(new URL(import.meta.url).pathname), "..");
const SPEC_PATH = join(ROOT, "packages/rpc/openapi.json");
const OUTPUT_DIR = join(ROOT, "apps/docs/src/content/docs/api");
const OUTPUT_PATH = join(OUTPUT_DIR, "reference.md");

const GENERATED_NOTICE =
  "<!-- Generated by `bun reptar docs:gen` from packages/rpc/openapi.json. Do not edit. -->";

const METHOD_ORDER = ["get", "post", "put", "patch", "delete"] as const;

interface OpenApiSchema {
  $ref?: string;
  type?: string;
  format?: string;
  items?: OpenApiSchema;
  properties?: Record<string, OpenApiSchema>;
  required?: string[];
  enum?: unknown[];
  oneOf?: OpenApiSchema[];
  anyOf?: OpenApiSchema[];
  minLength?: number;
  maxLength?: number;
  minimum?: number;
  maximum?: number;
  pattern?: string;
}

interface OpenApiOperation {
  summary?: string;
  parameters?: { name?: string; in?: string; schema?: OpenApiSchema }[];
  requestBody?: {
    content?: Record<string, { schema?: OpenApiSchema }>;
  };
  responses?: Record<
    string,
    { content?: Record<string, { schema?: OpenApiSchema }> }
  >;
}

interface OpenApiSpec {
  openapi?: string;
  info?: { title?: string; version?: string };
  paths?: Record<string, Record<string, OpenApiOperation>>;
  components?: { schemas?: Record<string, OpenApiSchema> };
}

const loadSpec = (): OpenApiSpec => {
  if (!existsSync(SPEC_PATH)) {
    throw new Error(
      `${SPEC_PATH} not found. Run \`bun reptar codegen\` first to generate the OpenAPI contract.`
    );
  }
  return JSON.parse(readFileSync(SPEC_PATH, "utf-8")) as OpenApiSpec;
};

const schemaNameOf = (schema: OpenApiSchema | undefined): string | undefined =>
  schema?.$ref?.split("/").pop();

const renderType = (schema: OpenApiSchema | undefined): string => {
  if (!schema) {
    return "unknown";
  }
  const refName = schemaNameOf(schema);
  if (refName) {
    return refName;
  }
  const union = schema.oneOf ?? schema.anyOf;
  if (union) {
    return union.map(renderType).join(" \\| ");
  }
  if (schema.type === "array") {
    return `${renderType(schema.items)}[]`;
  }
  if (schema.enum) {
    return schema.enum.map(String).join(" \\| ");
  }
  return schema.type ?? "unknown";
};

const renderConstraints = (schema: OpenApiSchema | undefined): string => {
  if (!schema) {
    return "—";
  }
  const parts: string[] = [];
  if (schema.format) {
    parts.push(`format: ${schema.format}`);
  }
  if (schema.minLength !== undefined) {
    parts.push(`minLength: ${schema.minLength}`);
  }
  if (schema.maxLength !== undefined) {
    parts.push(`maxLength: ${schema.maxLength}`);
  }
  if (schema.minimum !== undefined) {
    parts.push(`minimum: ${schema.minimum}`);
  }
  if (schema.maximum !== undefined) {
    parts.push(`maximum: ${schema.maximum}`);
  }
  if (schema.pattern) {
    parts.push(`pattern: ${schema.pattern}`);
  }
  return parts.length > 0 ? parts.join(", ") : "—";
};

const requestBodySchemaOf = (
  operation: OpenApiOperation
): OpenApiSchema | undefined =>
  operation.requestBody?.content?.["application/json"]?.schema;

const collectReferencedSchemaNames = (
  schema: OpenApiSchema | undefined,
  into: Set<string>,
  spec: OpenApiSpec
): void => {
  const refName = schemaNameOf(schema);
  if (refName) {
    if (into.has(refName)) {
      return;
    }
    into.add(refName);
    for (const property of Object.values(
      spec.components?.schemas?.[refName]?.properties ?? {}
    )) {
      collectReferencedSchemaNames(property, into, spec);
    }
    return;
  }
  for (const member of schema?.oneOf ?? schema?.anyOf ?? []) {
    collectReferencedSchemaNames(member, into, spec);
  }
  if (schema?.items) {
    collectReferencedSchemaNames(schema.items, into, spec);
  }
  for (const property of Object.values(schema?.properties ?? {})) {
    collectReferencedSchemaNames(property, into, spec);
  }
};

const renderSchemaTable = (name: string, spec: OpenApiSpec): string => {
  const schema = spec.components?.schemas?.[name];
  const properties = schema?.properties ?? {};
  const required = new Set(schema?.required ?? []);

  if (properties === undefined || Object.keys(properties).length === 0) {
    return "";
  }

  const rows = Object.entries(properties).map(
    ([propertyName, propertySchema]) =>
      `| \`${propertyName}\` | ${renderType(propertySchema)} | ${
        required.has(propertyName) ? "yes" : "—"
      } | ${renderConstraints(propertySchema)} |`
  );

  return `| Property | Type | Required | Constraints |
| --- | --- | --- | --- |
${rows.join("\n")}`;
};

const sortMethods = (a: string, b: string): number => {
  const indexA = METHOD_ORDER.indexOf(a as (typeof METHOD_ORDER)[number]);
  const indexB = METHOD_ORDER.indexOf(b as (typeof METHOD_ORDER)[number]);
  return (
    (indexA === -1 ? METHOD_ORDER.length : indexA) -
    (indexB === -1 ? METHOD_ORDER.length : indexB)
  );
};

interface Operation {
  method: string;
  path: string;
  operation: OpenApiOperation;
}

const flattenOperations = (spec: OpenApiSpec): Operation[] => {
  const operations: Operation[] = [];
  for (const [routePath, pathItem] of Object.entries(spec.paths ?? {})) {
    for (const [method, operation] of Object.entries(pathItem)) {
      operations.push({ method, operation, path: routePath });
    }
  }
  operations.sort(
    (a, b) => a.path.localeCompare(b.path) || sortMethods(a.method, b.method)
  );
  return operations;
};

const groupOf = (routePath: string): string =>
  routePath.split("/")[1]?.trim() || "root";

const renderOperation = (
  { method, operation, path: routePath }: Operation,
  spec: OpenApiSpec
): string => {
  const sections: string[] = [`### ${method.toUpperCase()} ${routePath}`];

  if (operation.summary) {
    sections.push("", operation.summary);
  }

  const parameters = (operation.parameters ?? []).filter(
    (parameter) => parameter.in === "path"
  );
  if (parameters.length > 0) {
    sections.push(
      "",
      `Path parameters: ${parameters
        .map(
          (parameter) =>
            `\`${parameter.name}\` (${renderType(parameter.schema)})`
        )
        .join(", ")}`
    );
  }

  const bodySchema = requestBodySchemaOf(operation);
  const bodySchemaName = schemaNameOf(bodySchema);
  if (bodySchemaName) {
    sections.push("", `Request body: \`${bodySchemaName}\``);
    const table = renderSchemaTable(bodySchemaName, spec);
    if (table) {
      sections.push("", table);
    }
  }

  const responses = Object.entries(operation.responses ?? {})
    .map(([status, response]) => {
      const responseSchema = response.content?.["application/json"]?.schema;
      const responseSchemaName = schemaNameOf(responseSchema);
      return `${status}${
        responseSchemaName ? ` → \`${responseSchemaName}\`` : ""
      }`;
    })
    .join(" · ");
  if (responses) {
    sections.push("", `**Responses:** ${responses}`);
  }

  return sections.join("\n");
};

const renderPage = (spec: OpenApiSpec): string => {
  const operations = flattenOperations(spec);
  const referencedSchemas = new Set<string>();
  for (const operation of operations) {
    collectReferencedSchemaNames(
      requestBodySchemaOf(operation.operation),
      referencedSchemas,
      spec
    );
    for (const response of Object.values(operation.operation.responses ?? {})) {
      collectReferencedSchemaNames(
        response.content?.["application/json"]?.schema,
        referencedSchemas,
        spec
      );
    }
  }

  const groups = new Map<string, Operation[]>();
  for (const operation of operations) {
    const group = groupOf(operation.path);
    const bucket = groups.get(group) ?? [];
    bucket.push(operation);
    groups.set(group, bucket);
  }

  const summaryRows = operations.map(
    ({ method, operation, path: routePath }) => {
      const bodySchemaName = schemaNameOf(requestBodySchemaOf(operation));
      const responses = Object.keys(operation.responses ?? {}).join(", ");
      return `| ${method.toUpperCase()} | \`${routePath}\` | ${
        bodySchemaName ? `\`${bodySchemaName}\`` : "—"
      } | ${responses || "—"} |`;
    }
  );

  const groupSections = [...groups.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([group, groupOperations]) => {
      const body = groupOperations
        .map((operation) => renderOperation(operation, spec))
        .join("\n\n");
      return `## \`${group}\`\n\n${body}`;
    });

  const schemaSections = [...referencedSchemas].sort().map((name) => {
    const table = renderSchemaTable(name, spec);
    return table
      ? `### ${name}\n\n${table}`
      : `### ${name}\n\n_No properties._`;
  });

  const openapiVersion = spec.openapi ?? "3.1";
  const specTitle = spec.info?.title ?? "Reptar API";

  return `---
title: "Blog API Reference"
description: "Auto-generated reference for the blog example app's API — every route, request schema, and response shape, straight from the OpenAPI ${openapiVersion} contract produced by bun reptar codegen."
---

${GENERATED_NOTICE}

The [blog example app](https://github.com/RocktownLabs/reptar/tree/main/examples/blog) is Reptar's living reference application. This page is generated from its OpenAPI ${openapiVersion} contract — the same artifact emitted to \`packages/rpc/openapi.json\` by \`bun reptar codegen\` — so it cannot drift from the C# route tree. For your own app, run \`app.UseScalar()\` to serve an interactive version of this reference at \`/reference\`.

Contract: \`${specTitle}\` (OpenAPI ${openapiVersion}, ${operations.length} operations).

## Route summary

| Method | Path | Request body | Responses |
| --- | --- | --- | --- |
${summaryRows.join("\n")}

${groupSections.join("\n\n")}

## Schema reference

${schemaSections.join("\n\n")}
`;
};

export const generateApiDocs = (): void => {
  const spec = loadSpec();
  const output = renderPage(spec);

  mkdirSync(OUTPUT_DIR, { recursive: true });
  writeFileSync(OUTPUT_PATH, output, "utf-8");

  const operations = flattenOperations(spec);
  console.log(
    `✓ Generated ${join("apps/docs/src/content/docs/api", "reference.md")} from packages/rpc/openapi.json (${operations.length} operations)`
  );
};

if (import.meta.main) {
  generateApiDocs();
}
