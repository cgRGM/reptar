#!/usr/bin/env bun
/* oxlint-disable eslint(complexity) -- one pass over three syntax forms */
/**
 * json-context — build-time JSON metadata for AOT/Wasm apps.
 *
 * A Roslyn source generator cannot feed the System.Text.Json source generator
 * (generators do not see each other's output). This script runs before the
 * build, scans the app's C# for [ReptarEntity], Rule<T>, and Produces<T>
 * types, and writes json-context.g.cs as ordinary source. The STJ generator
 * then sees it and emits the real JsonSerializerContext implementation.
 */

import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";

const CONTEXT_FILE = "json-context.g.cs";
const CONTEXT_NAME = "ReptarGeneratedJsonContext";

const primitives = new Set([
  "bool",
  "byte",
  "char",
  "decimal",
  "double",
  "float",
  "int",
  "long",
  "object",
  "short",
  "string",
  "uint",
  "ulong",
  "ushort",
  "DateTime",
  "DateTimeOffset",
  "Guid",
  "TimeSpan",
]);

const collectCs = (dir: string): string[] => {
  const files: string[] = [];
  for (const entry of readdirSync(dir)) {
    if (
      entry === "bin" ||
      entry === "obj" ||
      entry === "node_modules" ||
      entry === ".git"
    ) {
      continue;
    }
    const full = path.join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      files.push(...collectCs(full));
    } else if (entry.endsWith(".cs") && entry !== CONTEXT_FILE) {
      files.push(full);
    }
  }
  return files;
};

const namespaceOf = (content: string): string | null => {
  const match = content.match(/^\s*namespace\s+(?<namespace>[\w.]+)\s*[;{]/mu);
  return match?.groups?.namespace ?? null;
};

const qualify = (type: string, namespace: string | null): string | null => {
  let name = type.trim();
  let suffix = "";

  while (name.endsWith("[]")) {
    suffix += "[]";
    name = name.slice(0, -2).trim();
  }

  if (primitives.has(name) || name.length === 0 || name.includes("<")) {
    return null;
  }

  let full = name;
  if (!name.includes(".") && namespace) {
    full = `${namespace}.${name}`;
  }

  return `global::${full}${suffix}`;
};

export interface JsonContextResult {
  changed: boolean;
  file: string;
  types: string[];
}

const addType = (
  types: Set<string>,
  raw: string | undefined,
  namespace: string | null
): void => {
  const type = qualify(raw ?? "", namespace);
  if (type) {
    types.add(type);
  }
};

const collectTypes = (files: string[]): Set<string> => {
  const types = new Set<string>();

  for (const file of files) {
    const content = readFileSync(file, "utf-8");
    const namespace = namespaceOf(content);

    for (const match of content.matchAll(
      /\[ReptarEntity(?:\([^\]]*\))?\]\s*(?:public|internal)?\s*(?:sealed\s+)?(?:partial\s+)?(?:record|class)\s+(?<type>[A-Za-z_]\w*)/gu
    )) {
      addType(types, match.groups?.type, namespace);
    }

    for (const match of content.matchAll(
      /\bRule\s*<\s*(?<type>[A-Za-z_][\w.]*)\s*>/gu
    )) {
      addType(types, match.groups?.type, namespace);
    }

    for (const match of content.matchAll(
      /\bProduces\s*<\s*(?<type>[A-Za-z_][\w.[\]]*)\s*>/gu
    )) {
      addType(types, match.groups?.type, namespace);
    }
  }

  return types;
};

export const generateJsonContext = (
  appRoot: string,
  options: { dryRun?: boolean } = {}
): JsonContextResult => {
  const files = collectCs(appRoot);
  const types = collectTypes(files);
  const expanded = new Set<string>();
  for (const type of types) {
    expanded.add(type);
    if (!(type.endsWith("[]") || type.includes("<"))) {
      expanded.add(`global::System.Collections.Generic.List<${type}>`);
    }
  }

  const sorted = [...expanded].toSorted();
  const target = path.join(appRoot, CONTEXT_FILE);

  if (sorted.length === 0) {
    return { changed: false, file: target, types: [] };
  }

  const lines = [
    "// <auto-generated/>",
    "#nullable enable",
    "",
    "[global::System.Text.Json.Serialization.JsonSourceGenerationOptions(" +
      "PropertyNamingPolicy = global::System.Text.Json.Serialization.JsonKnownNamingPolicy.CamelCase)]",
  ];

  for (const type of sorted) {
    lines.push(
      `[global::System.Text.Json.Serialization.JsonSerializable(typeof(${type}))]`
    );
  }

  lines.push(
    `public sealed partial class ${CONTEXT_NAME} : ` +
      "global::System.Text.Json.Serialization.JsonSerializerContext;",
    "",
    `file static class __Register${CONTEXT_NAME}`,
    "{",
    "    [global::System.Runtime.CompilerServices.ModuleInitializer]",
    "    internal static void Init()",
    "    {",
    `        global::Reptar.ReptarJson.RegisterContext(${CONTEXT_NAME}.Default);`,
    "    }",
    "}",
    ""
  );

  const content = lines.join("\n");
  const previous = existsSync(target) ? readFileSync(target, "utf-8") : "";
  const changed = previous !== content;

  if (changed && !options.dryRun) {
    writeFileSync(target, content, "utf-8");
  }

  return { changed, file: target, types: sorted };
};

export const ensureJsonContextInclude = (
  appRoot: string,
  options: { dryRun?: boolean } = {}
): boolean => {
  const appCs = path.join(appRoot, "app.cs");
  if (!existsSync(appCs)) {
    return false;
  }

  const content = readFileSync(appCs, "utf-8");
  if (content.includes(`#:include ${CONTEXT_FILE}`)) {
    return false;
  }

  const lines = content.split("\n");
  const includeIndexes = lines
    .map((line, index) =>
      line.trimStart().startsWith("#:include ") ? index : -1
    )
    .filter((index) => index >= 0);
  const lastInclude = includeIndexes.at(-1) ?? -1;

  lines.splice(lastInclude + 1, 0, `#:include ${CONTEXT_FILE}`);

  if (!options.dryRun) {
    writeFileSync(appCs, lines.join("\n"), "utf-8");
  }

  return true;
};
