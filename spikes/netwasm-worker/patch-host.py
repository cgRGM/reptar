#!/usr/bin/env python3
"""Patch a NetWasm browser host into a Cloudflare Worker host.

This is a throwaway spike helper. The real host will be generated by
@reptar/host with these four Worker-specific behaviours built in.
"""

from pathlib import Path

BROWSER = Path(__file__).parent / "public" / "browser"
PAGE = BROWSER / "netwasm.page.mjs"
ENTRY = BROWSER / "HelloReptar.mjs"

replacements = [
    (
        'manifestUrl:new URL(`./deployment.json`,import.meta.url).href',
        "manifestUrl:globalThis.__REPTAR_MANIFEST_URL",
    ),
    (
        'manifestUrl:new URL("/browser/deployment.json",globalThis.location.origin).href',
        "manifestUrl:globalThis.__REPTAR_MANIFEST_URL",
    ),
    (
        "compileCoreModule:WebAssembly.compile.bind(WebAssembly)",
        "compileCoreModule:()=>globalThis.__REPTAR_WASM_MODULE",
    ),
    (
        "createModuleUrl:e=>URL.createObjectURL(new Blob([e],{type:`text/javascript`}))",
        'createModuleUrl:e=>"blob:reptar-raw-adapter"',
    ),
    (
        "importModule:e=>import(e)",
        'importModule:async()=>{const m=await import("./HelloReptar.raw-adapter.mjs");return{createAdapter:m.createAdapter,rawAdapterMetadata:m.rawAdapterMetadata}}',
    ),
    (
        "revokeModuleUrl:URL.revokeObjectURL.bind(URL)",
        "revokeModuleUrl:()=>{}",
    ),
]


def main() -> None:
    page = PAGE.read_text()
    applied = 0

    for old, new in replacements:
        if new in page:
            continue
        if old in page:
            page = page.replace(old, new)
            applied += 1

    PAGE.write_text(page)

    entry = ENTRY.read_text()
    if '"./netwasm.page.bun.mjs"' in entry:
        ENTRY.write_text(entry.replace('"./netwasm.page.bun.mjs"', '"./netwasm.page.mjs"'))

    print(f"patched {applied} host replacement(s)")


if __name__ == "__main__":
    main()
